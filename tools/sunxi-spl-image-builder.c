static int write_page(const struct image_info *info, uint8_t *buffer,
		      FILE *src, FILE *rnd, FILE *dst,
		      struct bch_control *bch, int page)
{
	int steps = info->usable_page_size / info->ecc_step_size;
	int eccbytes = DIV_ROUND_UP(info->ecc_strength * 14, 8);
	off_t pos = ftell(dst);
	size_t pad, cnt;
	int i;

	if (eccbytes % 2)
		eccbytes++;

	memset(buffer, 0xff, info->page_size + info->oob_size);
	cnt = fread(buffer, 1, info->usable_page_size, src);
	if (!cnt) {
		if (!feof(src)) {
			fprintf(stderr,
				"Failed to read data from the source\n");
			return -1;
		} else {
			return 0;
		}
	}

	fwrite(buffer, info->page_size + info->oob_size, 1, dst);

	for (i = 0; i < info->usable_page_size; i++) {
		if (buffer[i] !=  0xff)
			break;
	}

	/* We leave empty pages at 0xff. */
	if (i == info->usable_page_size)
		return 0;

	/* Restore the source pointer to read it again. */
	fseek(src, -cnt, SEEK_CUR);

	/* Randomize unused space if scrambling is required. */
	if (info->scramble) {
		int offs;

		if (info->boot0) {
			size_t ret;

			offs = steps * (info->ecc_step_size + eccbytes + 4);
			cnt = info->page_size + info->oob_size - offs;
			ret = fread(buffer + offs, 1, cnt, rnd);
			if (!ret && !feof(rnd)) {
				fprintf(stderr,
					"Failed to read random data\n");
				return -1;
			}
		} else {
			offs = info->page_size + (steps * (eccbytes + 4));
			cnt = info->page_size + info->oob_size - offs;
			memset(buffer + offs, 0xff, cnt);
			scramble(info, page, buffer + offs, cnt);
		}
		fseek(dst, pos + offs, SEEK_SET);
		fwrite(buffer + offs, cnt, 1, dst);
	}

	for (i = 0; i < steps; i++) {
		int ecc_offs, data_offs;
		uint8_t *ecc;

		memset(buffer, 0xff, info->ecc_step_size + eccbytes + 4);
		ecc = buffer + info->ecc_step_size + 4;
		if (info->boot0) {
			data_offs = i * (info->ecc_step_size + eccbytes + 4);
			ecc_offs = data_offs + info->ecc_step_size + 4;
		} else {
			data_offs = i * info->ecc_step_size;
			ecc_offs = info->page_size + 4 + (i * (eccbytes + 4));
		}

		//	0x0		0x404		0x404
		printf("data_offs=0x%x ecc_offs=0x%x ecc=0x%x\n",
		       data_offs, ecc_offs, ecc - buffer);
		//	140		1024		2048
		printf("eccbytes=%d ecc_step_size=%d page_size=%d\n",
		       eccbytes, info->ecc_step_size, info->page_size);

		cnt = fread(buffer, 1, info->ecc_step_size, src);
		if (!cnt && !feof(src)) {
			fprintf(stderr,
				"Failed to read data from the source\n");
			return -1;
		}

		pad = info->ecc_step_size - cnt;
		if (pad) {
			printf("padding=%d\n", pad);
			if (info->scramble && info->boot0) {
				size_t ret;

				ret = fread(buffer + cnt, 1, pad, rnd);
				if (!ret && !feof(rnd)) {
					fprintf(stderr,
						"Failed to read random data\n");
					return -1;
				}
			} else {
				memset(buffer + cnt, 0xff, pad);
			}
		}

		memset(ecc, 0, eccbytes);
		if (info->h6) {
			/* BBM taken from vendor code: FF 00 03 01 */
			buffer[info->ecc_step_size + 1] = 0;
			buffer[info->ecc_step_size + 2] = 3;
			buffer[info->ecc_step_size + 3] = 1;

			swap_bits(buffer, info->ecc_step_size + 4);

			encode_bch(bch, buffer, info->ecc_step_size + 4, ecc);

			for (int j=0; j <  4 + eccbytes; j++)
				printf("%02x ", buffer[info->ecc_step_size + j]);
			printf("\n");

			swap_bits(buffer, info->ecc_step_size + 4);
			swap_bits(ecc, eccbytes);

			for (int j=0; j <  4 + eccbytes; j++)
				printf("%02x ", buffer[info->ecc_step_size + j]);
			printf("\n");

			/*
			 * Scramble everything together: data + BBM + ECC
			 */
			scramble(info, page, buffer, info->ecc_step_size + 4 + eccbytes);
		} else {
			swap_bits(buffer, info->ecc_step_size + 4);
			encode_bch(bch, buffer, info->ecc_step_size + 4, ecc);
			swap_bits(buffer, info->ecc_step_size + 4);
			swap_bits(ecc, eccbytes);
			scramble(info, page, buffer, info->ecc_step_size + 4 + eccbytes);
		}

		fseek(dst, pos + data_offs, SEEK_SET);
		fwrite(buffer, info->ecc_step_size, 1, dst);
		fseek(dst, pos + ecc_offs - 4, SEEK_SET);
		fwrite(ecc - 4, eccbytes + 4, 1, dst);
	}

	/* Fix BBM. */
	fseek(dst, pos + info->page_size, SEEK_SET);
	memset(buffer, 0xff, 2);
	fwrite(buffer, 2, 1, dst);

	/* Make dst pointer point to the next page. */
	fseek(dst, pos + info->page_size + info->oob_size, SEEK_SET);

	return 0;
}

static int create_image(const struct image_info *info)
{
	off_t page = info->offset / info->page_size;
	struct bch_control *bch;
	FILE *src, *dst, *rnd;
	uint8_t *buffer;

	bch = init_bch(14, info->ecc_strength, BCH_PRIMITIVE_POLY);
	if (!bch) {
		fprintf(stderr, "Failed to init the BCH engine\n");
		return -1;
	}

	buffer = malloc(info->page_size + info->oob_size);
	if (!buffer) {
		fprintf(stderr, "Failed to allocate the NAND page buffer\n");
		return -1;
	}

	memset(buffer, 0xff, info->page_size + info->oob_size);

	src = fopen(info->source, "r");
	if (!src) {
		fprintf(stderr, "Failed to open source file (%s)\n",
			info->source);
		return -1;
	}

	dst = fopen(info->dest, "w");
	if (!dst) {
		fprintf(stderr, "Failed to open dest file (%s)\n", info->dest);
		return -1;
	}

	rnd = fopen("/dev/urandom", "r");
	if (!rnd) {
		fprintf(stderr, "Failed to open /dev/urandom\n");
		return -1;
	}

	/* Generate boot0 copies if requested */
	for (int copy = 0; copy < (info->boot0_copies > 0 ? info->boot0_copies : 1); copy++) {
		int pages_in_copy = 0;
		int page_in_copy = 0;  /* Relative page number within this copy for scrambling */

		/* Reset source file to beginning for each copy */
		if (copy > 0) {
			fseek(src, 0, SEEK_SET);
			clearerr(src);  /* Clear EOF flag */
		}

		while (1) {
			int ret;

			/* Check for EOF before trying to read */
			if (feof(src))
				break;

			/* Use relative page number within copy for scrambling (matches Allwinner BSP) */
			ret = write_page(info, buffer, src, rnd, dst, bch, page_in_copy);

			/* Check if write_page hit EOF (returns 0 when cnt==0 at EOF) */
			if (ret < 0) {
				return ret;  /* Error */
			}

			/* Check if we hit EOF during the read */
			if (feof(src)) {
				break;
			}

			/* Page was successfully written, increment counters */
			page_in_copy++;
			pages_in_copy++;
			page++;  /* Track absolute page for output file position */
		}

		/* Pad to pages_per_copy if specified by repeating source data */
		if (info->pages_per_copy > 0 && pages_in_copy < info->pages_per_copy) {
			/* For boot0, padding repeats from beginning of source */
			int data_pages = pages_in_copy;  /* Number of pages actually written from source */

			while (pages_in_copy < info->pages_per_copy) {
				int ret;
				/* Wrap around: repeat from beginning of source file */
				int repeat_page = (pages_in_copy - data_pages) % data_pages;
				fseek(src, repeat_page * info->usable_page_size, SEEK_SET);
				clearerr(src);

				/* Use repeat_page for scrambling to match the original page's scrambler seed */
				ret = write_page(info, buffer, src, rnd, dst, bch, repeat_page);
				if (ret < 0)
					return ret;
				/* Ignore EOF during padding - we're intentionally re-reading */
				pages_in_copy++;
				page++;
			}
		}
	}

	return 0;
}

