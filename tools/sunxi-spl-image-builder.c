static uint16_t brom_scrambler_seeds[] = { 0x4a80 };

static void scramble(const struct image_info *info,
		     int page, uint8_t *data, int datalen)
{
	uint16_t state;
	int i;

	printf("page=%d datalen=%d (0x%x)\n", page, datalen, datalen);
	/*
	 * Bail out earlier if the user didn't ask for scrambling.
	 * But Boot0 is always scrambled no matter the command line option.
	 */
	if (!info->boot0 && !info->scramble)
		return;

	/*
	 * On H6, the BROM scrambler seed is no different than the default one
	 */
	if (info->boot0 && !info->h6) {
		state = brom_scrambler_seeds[0];
	} else {
		unsigned seedmod;

		if (info->h6 && info->boot0) {
			/* H6 boot0 uses all 128 seeds */
			seedmod = ARRAY_SIZE(default_scrambler_seeds);
		} else {
			seedmod = info->eraseblock_size / info->page_size;
			if (seedmod > ARRAY_SIZE(default_scrambler_seeds))
				seedmod = ARRAY_SIZE(default_scrambler_seeds);
		}

		state = default_scrambler_seeds[page % seedmod];
	}

	/* Prepare the initial state... */
	state = lfsr_step(state, 15);

	/* and start scrambling data. */
	for (i = 0; i < datalen; i++) {
		data[i] ^= state;
		state = lfsr_step(state, 8);
	}
}

static void scramble_BBM(const struct image_info *info,
			 int page, uint8_t *oob, int datalen)
{
	uint16_t state;
	unsigned len;
	int i;

	/*
	 * Bail out earlier if the user didn't ask for scrambling.
	 * But Boot0 is always scrambled no matter the command line option.
	 */
	if (!info->boot0 && !info->scramble)
		return;

	len = sizeof(rand_factor_1st_spare_data) / sizeof(rand_factor_1st_spare_data[0]);

	for (int i = 0; i < datalen; i++) {
		oob[i] ^= rand_factor_1st_spare_data[i % len][page % 128];
	}
}

