static int check_image_info(struct image_info *info)
{
	static int ecc_strengths_a10[] = { 16, 24, 28, 32, 40, 48, 56, 60, 64 };
	static int ecc_strengths_h6[] = {
		16, 24, 28, 32, 40, 44, 48, 52, 56, 60, 64, 68, 72, 76, 80
	};
	int *valid_ecc_strengths;
	size_t nstrengths;
	int eccbytes, eccsteps;
	unsigned i;

	if (!info->page_size) {
		fprintf(stderr, "--page is missing\n");
		return -EINVAL;
	}

	if (!info->page_size) {
		fprintf(stderr, "--oob is missing\n");
		return -EINVAL;
	}

	if (!info->eraseblock_size) {
		fprintf(stderr, "--eraseblock is missing\n");
		return -EINVAL;
	}

	if (info->ecc_step_size != 512 && info->ecc_step_size != 1024) {
		fprintf(stderr, "Invalid ECC step argument: %d\n",
			info->ecc_step_size);
		return -EINVAL;
	}

	if (info->h6) {
		if (info->ecc_step_size != 1024) {
			fprintf(stderr,
				"H6 SoCs supports only 1024 bytes ECC step\n");
			return -EINVAL;
		}
		valid_ecc_strengths = ecc_strengths_h6;
		nstrengths = ARRAY_SIZE(ecc_strengths_h6);
	} else {
		valid_ecc_strengths = ecc_strengths_a10;
		nstrengths = ARRAY_SIZE(ecc_strengths_a10);
	}

	for (i = 0; i < nstrengths; i++) {
		if (valid_ecc_strengths[i] == info->ecc_strength)
			break;
	}

	if (i == nstrengths) {
		fprintf(stderr, "Invalid ECC strength argument: %d\n",
			info->ecc_strength);
		return -EINVAL;
	}

	eccbytes = DIV_ROUND_UP(info->ecc_strength * 14, 8);
	if (eccbytes % 2)
		eccbytes++;
	eccbytes += 4;

	eccsteps = info->usable_page_size / info->ecc_step_size;
	// eccbytes=144 eccsteps=1 usable_page_size=1024 ecc_step_size=1024
	printf("eccbytes=%d eccsteps=%d usable_page_size=%d ecc_step_size=%d\n",
	       eccbytes, eccsteps, info->usable_page_size, info->ecc_step_size);

	// 2048 + 128 < 1024 + 144
	if (info->page_size + info->oob_size <
	    info->usable_page_size + (eccsteps * eccbytes)) {
		fprintf(stderr,
			"ECC bytes do not fit in the NAND page, choose a weaker ECC\n");
		return -EINVAL;
	}

	/* Calculate pages_per_copy based on eraseblock size for boot0 copies */
	if (info->boot0_copies > 0 && info->eraseblock_size > 0) {
		/* For H6, boot0 uses 2 full eraseblocks per copy (128 pages per copy) */
		if (info->h6) {
			info->pages_per_copy = (info->eraseblock_size * 2) / info->page_size;
		} else {
			info->pages_per_copy = info->eraseblock_size / info->page_size;
		}
	}

	return 0;
}

int main(int argc, char **argv)
{
	struct image_info info;

	memset(&info, 0, sizeof(info));
	/*
	 * Process user arguments
	 */
	for (;;) {
		int option_index = 0;
		char *endptr = NULL;
		static const struct option long_options[] = {
			{"help", no_argument, 0, 'h'},
			{"ecc", required_argument, 0, 'c'},
			{"page", required_argument, 0, 'p'},
			{"oob", required_argument, 0, 'o'},
			{"usable", required_argument, 0, 'u'},
			{"eraseblock", required_argument, 0, 'e'},
			{"boot0", no_argument, 0, 'b'},
			{"scramble", no_argument, 0, 's'},
			{"address", required_argument, 0, 'a'},
			{"h6", no_argument, 0, '6'},
			{"copies", required_argument, 0, 'n'},
			{0, 0, 0, 0},
		};

		int c = getopt_long(argc, argv, "c:p:o:u:e:ba:sh6n:",
				long_options, &option_index);
		if (c == EOF)
			break;

		switch (c) {
		case 'h':
			display_help(0);
			break;
		case 's':
			info.scramble = 1;
			break;
		case 'c':
			info.ecc_strength = strtol(optarg, &endptr, 0);
			if (*endptr == '/')
				info.ecc_step_size = strtol(endptr + 1, NULL, 0);
			break;
		case 'p':
			info.page_size = strtol(optarg, NULL, 0);
			break;
		case 'o':
			info.oob_size = strtol(optarg, NULL, 0);
			break;
		case 'u':
			info.usable_page_size = strtol(optarg, NULL, 0);
			break;
		case 'e':
			info.eraseblock_size = strtol(optarg, NULL, 0);
			break;
		case 'b':
			info.boot0 = 1;
			break;
		case 'a':
			info.offset = strtoull(optarg, NULL, 0);
			break;
		case '6':
			info.h6 = 1;
			break;
		case 'n':
			info.boot0_copies = strtol(optarg, NULL, 0);
			break;
		case '?':
			display_help(-1);
			break;
		}
	}

	if ((argc - optind) != 2)
		display_help(-1);

	info.source = argv[optind];
	info.dest = argv[optind + 1];

	if (!info.boot0) {
		info.usable_page_size = info.page_size;
	} else if (!info.usable_page_size) {
		if (info.page_size > 8192)
			info.usable_page_size = 8192;
		else if (info.page_size > 4096)
			info.usable_page_size = 4096;
		else
			info.usable_page_size = 1024;
	}

	if (check_image_info(&info))
		display_help(-1);

	return create_image(&info);
}
